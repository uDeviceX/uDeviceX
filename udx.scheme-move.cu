__global__ void update(float dt, float mass, Particle* pp, const Force *ff, int n) {
    float *r, *v;
    const float *f;
    int pid;
    pid = threadIdx.x + blockDim.x * blockIdx.x;
    if (pid >= n) return;

    r = pp[pid].r;
    v = pp[pid].v;
    f = ff[pid].f;
    update0(dt, mass, f, /**/ r, v);
}

